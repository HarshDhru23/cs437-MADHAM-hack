"""Write frontend/src/features/import/syntheticSample.ts: the IMS-style grade table behind the "synthetic example" the page offers. It is the made-up student of
`data/demo/sample-student.json` (real course codes, invented grades, 92 credits), so there is one student and one source: the table the page pastes and the
record the sample button creates cannot drift apart (a test regenerates it and compares).

    python scripts/gen_synthetic_sample.py          # rewrite the file
    python scripts/gen_synthetic_sample.py --check  # exit 1 when the file is out of date
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'data' / 'demo' / 'sample-student.json'
TARGET = ROOT / 'frontend' / 'src' / 'features' / 'import' / 'syntheticSample.ts'
HEADER = 'Academic Period\tCourse No\tCourse Name\tCredit\tGrade'
SEMESTER = {'I': 'Semester I', 'II': 'Semester II', 'SUMMER': 'Summer'}


def period(term_id):
    year, _, kind = term_id.rpartition('-')
    return f'{year} {SEMESTER[kind]}'


def term_order(term_id):
    year, _, kind = term_id.rpartition('-')
    return (int(year[:4]), {'I': 1, 'II': 2, 'SUMMER': 3}[kind])


def ims_table():
    """Newest semester first, like IMS; inside a semester the order of the data file."""
    attempts = json.loads(SOURCE.read_text(encoding='utf-8'))['attempts']
    ordered = sorted(enumerate(attempts), key=lambda pair: (term_order(pair[1]['term_id']), -pair[0]), reverse=True)
    rows = [HEADER] + [f"{period(a['term_id'])}\t{a['normalized_code']}\t{a['title']}\t{a['credits']}\t{a['grade']}" for _, a in ordered]
    return '\n'.join(rows)


def source_text():
    return (
        '// Generated by scripts/gen_synthetic_sample.py from data/demo/sample-student.json. Do not edit by hand.\n'
        '// A made-up student in the IMS table layout: real course codes, invented grades, no real person.\n'
        f'export const SYNTHETIC_SAMPLE = {json.dumps(ims_table())};\n'
    )


if __name__ == '__main__':
    text = source_text()
    if '--check' in sys.argv:
        sys.exit(0 if TARGET.exists() and TARGET.read_text(encoding='utf-8').replace('\r\n', '\n') == text else 1)
    TARGET.write_text(text, encoding='utf-8', newline='\n')
    print('wrote', TARGET.relative_to(ROOT), len(text.splitlines()), 'lines')
